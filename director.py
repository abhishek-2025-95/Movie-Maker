def _enrich_visual_prompt(visual: str, narration: str, topic: str, style: str = "live") -> str:
    blob = f"{topic} {narration} {visual}".lower()
    parts = [visual.strip()]

    if style == "animated":
        parts.append(
            "cinematic anime still, Netflix animation quality, emotional lighting, "
            "consistent character design, detailed eyes and hair"
        )
    else:
        dark_keys = (
            "mystery", "mysterious", "dark", "secret", "disappear", "missing", "death",
            "danger", "fear", "eerie", "haunted", "crash", "bermuda", "triangle",
            "conspiracy", "horror", "tragedy", "lost", "vanish", "storm", "jumpscare",
            "tomb", "egypt", "egyptian", "artifact", "archaeolog", "relic", "dread",
            "रहस्य", "खतरा", "गायब", "अंधेरा", "डर",
        )
        if any(k.lower() in blob for k in dark_keys):
            # Avoid modern fluorescents on ancient/tomb topics (Act-3 DNA leak)
            if any(k in blob for k in ("tomb", "egypt", "egyptian", "hieroglyph", "artifact", "archaeolog", "relic")):
                parts.append(
                    "directed thriller cinematography, low-key lighting, dramatic shadow play, "
                    "claustrophobic framing, torch and oil-lamp practicals, sandstone texture, "
                    "35mm film grain, single subject only, intentional negative space"
                )
            else:
                parts.append(
                    "directed horror cinematography, low-key lighting, dramatic shadow play, "
                    "claustrophobic framing, dim corridor practicals, "
                    "35mm film grain, single subject only, intentional negative space"
                )

    # Word-boundary match only — substring "love" in "gloves" was leaking romance into thrillers
    love_keys = ("love", "romance", "romantic", "heart", "प्यार", "इश्क", "मोहब्बत", "प्रेम")
    if any(re.search(rf"\b{re.escape(k)}\b", blob) for k in love_keys):
        parts.append(
            "romantic atmosphere, soft rim light, emotional intimacy, beautiful color grade"
        )

    parts.append("clean frame with no text, no letters, no watermark, no logo, no signage")
    return ", ".join(p for p in parts if p)


def _extract_json_object(raw_text: str) -> dict[str, Any]:
    """Parse model JSON; tolerate markdown fences / truncated tails."""
    text = (raw_text or "").strip()
    if text.startswith("```"):
        text = text.strip("`")
        if text.lower().startswith("json"):
            text = text[4:].lstrip()
    try:
        data = json.loads(text)
        if isinstance(data, dict):
            return data
    except json.JSONDecodeError:
        pass
    start = text.find("{")
    end = text.rfind("}")
    if start >= 0 and end > start:
        snippet = text[start : end + 1]
        try:
            data = json.loads(snippet)
            if isinstance(data, dict):
                return data
        except json.JSONDecodeError:
            pass
    raise json.JSONDecodeError("Could not parse screenplay JSON", text, 0)


def _with_trinity(
    sp: Screenplay,
    *,
    character_bible: str,
    location_lock: str,
    prop_bible: str,
    lighting_bible: str = "",
) -> Screenplay:
    sp.character_bible = character_bible
    sp.location_lock = location_lock
    sp.prop_bible = prop_bible
    if lighting_bible:
        sp.lighting_bible = lighting_bible
    raw = dict(sp.raw or {})
    raw.update(
        {
            "character_bible": character_bible,
            "location_lock": location_lock,
            "prop_bible": prop_bible,
            "lighting_bible": sp.lighting_bible,
        }
    )
    sp.raw = raw
    return sp


def _with_transitions(scenes: list[Scene], transitions: list[str] | None = None) -> list[Scene]:
    """Attach transition_to_next; last scene always none."""
    out: list[Scene] = []
    n = len(scenes)
    for i, sc in enumerate(scenes):
        is_last = i == n - 1
        preset = None
        if transitions and i < len(transitions):
            preset = transitions[i]
        elif not is_last:
            preset = sc.transition_to_next
        out.append(
            Scene(
                narration=sc.narration,
                visual_prompt=sc.visual_prompt,
                motion_prompt=sc.motion_prompt,
                transition_to_next=normalize_transition(preset, is_last=is_last),
            )
        )
    return out


