@dataclass
class TopicJob:
    topic: str
    mode: str = config.DEFAULT_MODE
    ratio: str = config.DEFAULT_RATIO
    lang: str = config.DEFAULT_LANG
    style: str = config.DEFAULT_STYLE
    # story = normal 3-act LLM path; raw = 100% LLM-off, prompt-driven Reel
    director_mode: str = "story"


VALID_TRANSITIONS = ("hard_cut", "fade_to_black", "crossfade", "smash_cut", "none")


def normalize_transition(value: str | None, *, is_last: bool = False) -> str:
    """Map LLM / fallback transition keys; unknown → hard_cut. Final scene → none."""
    if is_last:
        return "none"
    raw = (value or "hard_cut").strip().lower().replace("-", "_").replace(" ", "_")
    aliases = {
        "fade": "fade_to_black",
        "fadeout": "fade_to_black",
        "fade_black": "fade_to_black",
        "cut": "hard_cut",
        "hard": "hard_cut",
        "cross_fade": "crossfade",
        "dissolve": "crossfade",
        "smash": "smash_cut",
        "jump": "smash_cut",
    }
    key = aliases.get(raw, raw)
    allowed = getattr(config, "VALID_TRANSITIONS", VALID_TRANSITIONS)
    if key in allowed and key != "none":
        return key
    return "hard_cut"


@dataclass
class Scene:
    narration: str
    visual_prompt: str
    motion_prompt: str = "slow cinematic camera push-in, subtle ambient motion"
    transition_to_next: str = "hard_cut"


@dataclass
class Screenplay:
    title: str
    scenes: list[Scene] = field(default_factory=list)
    raw: dict[str, Any] = field(default_factory=dict)
    # Dynamic Quad — generated by LLM, prepended to every visual_prompt
    character_bible: str = ""
    location_lock: str = ""
    prop_bible: str = ""
    lighting_bible: str = ""


_META_RE = re.compile(
    r"^(?:(?:mode|ratio|lang|style|pipeline)\s*:\s*[^\s|]+(?:\s+|\s*\|\s*))*",
    re.IGNORECASE,
)
_KV_RE = re.compile(r"(mode|ratio|lang|style|pipeline)\s*:\s*([^\s|]+)", re.IGNORECASE)
_TEXT_OVERLAY_RE = re.compile(
    r"\[TEXT\s*OVERLAY\]\s*(.*?)\s*(?:\[/TEXT\s*OVERLAY\]|(?=\[[A-Z])|$)",
    re.IGNORECASE | re.DOTALL,
)


def extract_text_overlay(topic: str) -> str:
    """Pull exact [TEXT OVERLAY] block from a raw prompt; empty if absent."""
    m = _TEXT_OVERLAY_RE.search(topic or "")
    if not m:
        return ""
    return " ".join((m.group(1) or "").split()).strip()


def strip_text_overlay_block(topic: str) -> str:
    """Remove [TEXT OVERLAY]… from visual topic body."""
    return _TEXT_OVERLAY_RE.sub(" ", topic or "").strip()


def parse_topic_line(line: str) -> TopicJob | None:
    text = line.strip()
    if not text or text.startswith("#"):
        return None

    meta: dict[str, str] = {}
    for match in _KV_RE.finditer(text):
        meta[match.group(1).lower()] = match.group(2).strip().lower()

    topic = _META_RE.sub("", text)
    topic = topic.lstrip("|").strip()
    if not topic:
        topic = _KV_RE.sub("", text).strip(" |")
    if not topic:
        return None

    mode = meta.get("mode", config.DEFAULT_MODE)
    ratio = meta.get("ratio", config.DEFAULT_RATIO)
    lang = meta.get("lang", config.DEFAULT_LANG)
    style = meta.get("style", config.DEFAULT_STYLE)
    director_mode = "story"
    if mode == "raw" or meta.get("pipeline") == "raw":
        director_mode = "raw"
        mode = "faceless"

    if mode not in {"faceless", "character"}:
        mode = config.DEFAULT_MODE
    if ratio not in config.RATIO_SIZES:
        ratio = config.DEFAULT_RATIO
    if lang not in {"en", "hi"}:
        lang = config.DEFAULT_LANG
    if style not in config.STYLE_SUFFIX:
        style = config.DEFAULT_STYLE
    # Hard rule: no anime/animated output unless ALLOW_ANIMATED is explicitly True
    if style == "animated" and not getattr(config, "ALLOW_ANIMATED", False):
        style = "live"

    return TopicJob(
        topic=topic,
        mode=mode,
        ratio=ratio,
        lang=lang,
        style=style,
        director_mode=director_mode,
    )


def load_topics(path=None) -> list[TopicJob]:
    path = path or config.TOPICS_FILE
    jobs: list[TopicJob] = []
    for line in path.read_text(encoding="utf-8").splitlines():
        job = parse_topic_line(line)
        if job:
            jobs.append(job)
    return jobs


def style_prompts(style: str) -> tuple[str, str]:
    style = style if style in config.STYLE_SUFFIX else config.DEFAULT_STYLE
    # Flux stills always use the hardcoded cinematic negative
    neg = getattr(config, "FLUX_NEGATIVE_PROMPT", None) or config.STYLE_NEGATIVE[style]
    return config.STYLE_SUFFIX[style], neg


