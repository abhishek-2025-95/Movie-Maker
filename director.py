def topic_implies_solitary(topic: str) -> bool:
    t = (topic or "").lower()
    keys = (
        "solitary", "alone", "lone ", "lone.", "single ", "isolated",
        "one archaeologist", "a solitary", "by herself", "by himself",
    )
    return any(k in t for k in keys)


