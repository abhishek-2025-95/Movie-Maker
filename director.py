def generate_screenplay(job: TopicJob, scene_count: int | None = None) -> Screenplay:
    n = scene_count or config.SCENES_PER_VIDEO
    topic_l = job.topic.lower()
    # --mode raw / pipeline:raw → LLM fully disabled
    if getattr(job, "director_mode", "story") == "raw":
        return _build_raw_screenplay(job)
    # Locked full-song lyric music video (before love/horror LLM paths)
    if _is_music_video_lyric_topic(job.topic):
        return _fallback_music_video_lyric(job)
    # Locked USA sports quiz Reel (before LLM)
    if _is_usa_sports_quiz_topic(job.topic):
        return _fallback_usa_sports_quiz(job)
    # Locked 15s wingsuit action (before LLM — kills Act-2 drama leak)
    if _is_wingsuit_canyon_topic(job.topic):
        return _fallback_wingsuit_canyon(job)
    # Locked 12s analog-horror phone reel (before generic hospital horror)
    if _is_analog_phone_reel_topic(job.topic):
        return _fallback_analog_phone_reel(job)
    # Locked cinematic dinner date (before generic love — needs anti-kiss / empty room)
    if _is_dinner_date_topic(job.topic):
        sp = _fallback_dinner_date_screenplay(job)
        if n and len(sp.scenes) > n:
            sp.scenes = _with_transitions(sp.scenes[:n])
        return sp
    # Locked cinematic romance — photoreal 8-beat ~120s (priority over generic LLM for love topics)
    love_keys = ("love", "romance", "romantic", "metro love", "प्यार", "इश्क", "मोहब्बत", "प्रेम", "लव")
    if any(k in topic_l or k in job.topic for k in love_keys):
        sp = _fallback_love_screenplay(job)
        # Timed 120s romance keeps full beat sheet — never truncate to SCENES_PER_VIDEO
        if (sp.raw or {}).get("reel_profile") == "romance_love_120s":
            return sp
        if n and len(sp.scenes) > n:
            sp.scenes = _with_transitions(sp.scenes[:n])
        return sp
    # Locked cinematic horror arc when topic is explicitly horror (still 3-act, paced)
    if "horror" in topic_l or "jumpscare" in topic_l or "jump scare" in topic_l:
        sp = _fallback_horror_screenplay(job)
        if n and len(sp.scenes) > n:
            if n == 3 and len(sp.scenes) >= 6:
                sp.scenes = _with_transitions(
                    [sp.scenes[0], sp.scenes[2], sp.scenes[5]],
                    ["hard_cut", "smash_cut", "none"],
                )
            else:
                sp.scenes = _with_transitions(sp.scenes[:n])
        return sp
    # Sci-fi / thriller: try live LLM first (strict JSON + retries), fallback only after failure
    scifi_keys = (
        "rogue ai", "server farm", "artificial intelligence", "ai awakening",
        "cyber", "android", "neon", "detective", "noir",
    )
    prefers_scifi_fallback = any(k in topic_l for k in scifi_keys) or (
        "ai" in topic_l and "server" in topic_l
    )

    system = _director_system_prompt(job, n)
    payload = {
        "model": config.OLLAMA_MODEL,
        "prompt": f"{system}\n\nTopic: {job.topic}\n\nRespond with JSON only.",
        "format": "json",  # enforce strict JSON from Ollama
        "stream": False,
        "options": {"temperature": 0.55},
    }
    max_retries = max(3, int(getattr(config, "OLLAMA_MAX_RETRIES", 3)))
    last_err: Exception | None = None
    for attempt in range(max_retries):
        try:
            resp = requests.post(config.OLLAMA_URL, json=payload, timeout=600)
            resp.raise_for_status()
            body = resp.json()
            raw_text = body.get("response") or "{}"
            data = _extract_json_object(raw_text)
            if not isinstance(data, dict):
                raise ValueError(f"Ollama JSON was not an object (attempt {attempt + 1})")
            screenplay = _parse_screenplay(data, job.topic, job.style)
            if screenplay.scenes and all(
                (s.narration or "").strip() and (s.visual_prompt or "").strip()
                for s in screenplay.scenes
            ):
                if n and len(screenplay.scenes) > n:
                    screenplay.scenes = screenplay.scenes[:n]
                screenplay.raw = {
                    **(screenplay.raw or {}),
                    "fallback": False,
                    "ollama_attempts": attempt + 1,
                }
                return screenplay
            last_err = ValueError(
                f"Empty/invalid scenes from Ollama (attempt {attempt + 1}/{max_retries}): "
                f"{raw_text[:240]}"
            )
        except (requests.RequestException, json.JSONDecodeError, ValueError, TypeError, KeyError) as exc:
            last_err = exc
            # Cooler retry — more deterministic JSON
            payload["options"] = {"temperature": 0.2 if attempt >= 1 else 0.35}
            continue
    # Last-resort production fallback ONLY after all retries fail
    if prefers_scifi_fallback or any(
        k in topic_l for k in ("ai", "server", "neon", "detective", "noir", "cyber")
    ):
        return _fallback_scifi_screenplay(job)
    raise RuntimeError(f"Director screenplay failed after {max_retries} retries: {last_err}")


def _flatten_prompt_field(value: Any) -> str:
    """Normalize LLM visual/motion fields that sometimes arrive as nested dict/list."""
    if value is None:
        return ""
    if isinstance(value, str):
        return value.strip()
    if isinstance(value, dict):
        parts: list[str] = []
        # Prefer cinematic keys in a readable order
        for key in (
            "location",
            "setting",
            "characters",
            "character",
            "wardrobe",
            "face",
            "camera_movement",
            "camera",
            "lighting_cues",
            "lighting",
            "mood",
            "negative_emotional_keywords",
            "action",
            "description",
            "prompt",
        ):
            if key not in value:
                continue
            v = value[key]
            if isinstance(v, dict):
                parts.append(", ".join(f"{kk} {vv}" for kk, vv in v.items() if vv))
            elif isinstance(v, (list, tuple)):
                parts.append(", ".join(str(x) for x in v if x))
            elif v not in (None, True, False, ""):
                parts.append(str(v))
        # Booleans like photorealistic/cinematic/8k
        for key, v in value.items():
            if v is True:
                parts.append(str(key).replace("_", " "))
        leftover = []
        for key, v in value.items():
            if key in {
                "location", "setting", "characters", "character", "wardrobe", "face",
                "camera_movement", "camera", "lighting_cues", "lighting", "mood",
                "negative_emotional_keywords", "action", "description", "prompt",
            }:
                continue
            if v is True or v is False or v is None:
                continue
            if isinstance(v, (dict, list, tuple)):
                continue
            leftover.append(str(v))
        parts.extend(leftover)
        return ", ".join(p for p in parts if p)
    if isinstance(value, (list, tuple)):
        return ", ".join(_flatten_prompt_field(x) for x in value if x)
    return str(value).strip()


def _parse_screenplay(
    data: dict[str, Any],
    fallback_title: str,
    style: str = "live",
) -> Screenplay:
    scenes_raw = data.get("scenes") or []
    character_bible, location_lock, prop_bible, lighting_bible = _extract_trinity(
        data, fallback_title
    )
    # Identity lock for scenes = dynamic character_bible (NOT static duo config)
    character_lock = character_bible
    scenes: list[Scene] = []
    for item in scenes_raw:
        if not isinstance(item, dict):
            continue
        narration = str(item.get("narration") or "").strip()
        visual = _flatten_prompt_field(item.get("visual_prompt") or item.get("visual") or "")
        motion = _flatten_prompt_field(item.get("motion_prompt") or item.get("motion") or "")
        # Pull camera language from visual into motion if motion empty
        if not motion and visual:
            for cue in (
                "dolly zoom",
                "slow pan",
                "push-in",
                "push in",
                "handheld",
                "crane",
                "tracking",
                "static hold",
            ):
                if cue in visual.lower():
                    motion = cue
                    break
        if not narration and not visual:
            continue
        # Trinity prepend happens in pipeline — keep visual focused here
        if character_lock and character_lock.lower() not in visual.lower():
            visual = f"{character_lock}, {visual}" if visual else character_lock
        if "photorealistic" not in visual.lower():
            visual = f"{visual}, photorealistic, cinematic, 8k"
        visual = _enrich_visual_prompt(
            visual or "cinematic establishing shot",
            narration,
            fallback_title,
            style=style,
        )
        transition = normalize_transition(str(item.get("transition_to_next") or "hard_cut"))
        scenes.append(
            Scene(
                narration=narration or "...",
                visual_prompt=visual,
                motion_prompt=motion or "slow cinematic camera push-in, subtle ambient motion",
                transition_to_next=transition,
            )
        )
    scenes = _with_transitions(scenes)
    title = str(data.get("title") or fallback_title).strip()
    raw = dict(data) if isinstance(data, dict) else {}
    raw.update(
        {
            "character_bible": character_bible,
            "location_lock": location_lock,
            "prop_bible": prop_bible,
            "lighting_bible": lighting_bible,
        }
    )
    return Screenplay(
        title=title,
        scenes=scenes,
        raw=raw,
        character_bible=character_bible,
        location_lock=location_lock,
        prop_bible=prop_bible,
        lighting_bible=lighting_bible,
    )


